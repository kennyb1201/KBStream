# the logo lockup (transparent, for the README / website / anywhere vector)
# --------------------------------------------------------------------------- #

LOGO_W = 300.0
LOGO_H = 96.0


def logo_layers():
    mark_d = MARK_D
    word = wordmark(BOLD, "KBSTREAM", cap=29.0, tracking_em=0.05)
    word_w = bbox(word)[2] - bbox(word)[0]
    tag = fitted_line(MEDIUM, TAGLINE, cap=8.0, target_w=word_w)
