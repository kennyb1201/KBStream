#!/usr/bin/env python3
"""Generate KBStream's launcher branding: the Google TV banner, the app icons
and the logo lockup.

Why this exists instead of a hand-made PNG in res/: this container has no image
library and no SVG renderer, and the launcher assets have to be bitmaps --
a TV launcher rasters the banner itself, and `mipmap-anydpi-v26` alone leaves
every API 23-25 box (Fire OS 5/6, older Google TV sticks) with no icon asset at
all. So the artwork is defined ONCE here, as polygons plus gradients, in design
units, and then:

  * rasterized to PNG (analytic coverage across x, N sub-scanlines down y),
  * serialized to SVG for the repo/website,
  * serialized to vector-drawable XML for the adaptive icon's layers.

Everything is regenerated by running this file; there is no artwork to hand-edit.

The mark is the brass play button -- the ringed glyph a viewer already reads as
"watch something" -- defined once in the MARK_* constants and reused by the
icon, the banner, the lockup and the notification silhouette, so every surface
carries the same drawing. The wordmark is set in the app's own oswald_bold.ttf
through font_glyphs.py, so the letterforms are a designed typeface rather than
traced shapes, and the palette is the app's theme (void navy + the single brass
accent).

Usage:
    render_brand_assets.py                 # write every asset
    render_brand_assets.py --preview NAME  # rasterize one piece as ASCII
"""

