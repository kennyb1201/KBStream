# --------------------------------------------------------------------------- #
# paints: "solid" | "lin" (p0, p1, c0, c1) | "rad" (centre, r, colour, a, gamma)
# --------------------------------------------------------------------------- #

def with_alpha(c, a):
    """The same colour at a fraction of its alpha. The plate is drawn at full
    strength for the opaque outputs and faded for the translucent banner."""
    return (c[0], c[1], c[2], c[3] * a)


def solid(c):
    return ("solid", c)


def lin(p0, p1, c0, c1):
    return ("lin", p0, p1, c0, c1)


def rad(centre, r, colour, alpha, gamma=1.7):
    return ("rad", centre, r, colour, alpha, gamma)


def paint_at(p, x, y):
    kind = p[0]
    if kind == "solid":
        return p[1]
    if kind == "lin":
        (x0, y0), (x1, y1), c0, c1 = p[1], p[2], p[3], p[4]
        dx, dy = x1 - x0, y1 - y0
        den = dx * dx + dy * dy
        t = 0.0 if den == 0 else ((x - x0) * dx + (y - y0) * dy) / den
        t = 0.0 if t < 0 else (1.0 if t > 1 else t)
        return (
            c0[0] + (c1[0] - c0[0]) * t,
            c0[1] + (c1[1] - c0[1]) * t,
            c0[2] + (c1[2] - c0[2]) * t,
            c0[3] + (c1[3] - c0[3]) * t,
        )
    # radial: bright at the centre, fading to nothing at r
    (cx, cy), r, c, a, gamma = p[1], p[2], p[3], p[4], p[5]
    dx, dy = x - cx, y - cy
    d2 = dx * dx + dy * dy
    if d2 >= r * r:
        return (c[0], c[1], c[2], 0.0)
    t = 1.0 - math.sqrt(d2) / r
    return (c[0], c[1], c[2], a * t ** gamma)


def constant_in_x(p):
    """True when a paint only varies down the y axis (lets fill() hoist it)."""
    if p[0] == "solid":
        return True
    if p[0] == "lin":
        return abs(p[1][0] - p[2][0]) < 1e-9
    return False


def xf_paint(p, k, dx, dy):
    if p[0] == "lin":
        (x0, y0), (x1, y1) = p[1], p[2]
        return ("lin", (x0 * k + dx, y0 * k + dy), (x1 * k + dx, y1 * k + dy), p[3], p[4])
    if p[0] == "rad":
        (cx, cy) = p[1]
        return ("rad", (cx * k + dx, cy * k + dy), p[2] * k, p[3], p[4], p[5])
    return p


# --------------------------------------------------------------------------- #
# geometry: every shape is a closed polyline (curves are flattened with enough
# segments that the facets stay well under a quarter pixel)
# --------------------------------------------------------------------------- #

def _dist(a, b):
    return math.hypot(b[0] - a[0], b[1] - a[1])


def rounded_polygon(pts, r):
    """Fillet every corner of a convex polygon to radius r."""
    n = len(pts)
    out = []
    for i in range(n):
        prev, cur, nxt = pts[i - 1], pts[i], pts[(i + 1) % n]
        if r <= 1e-9:
            out.append(cur)
            continue
        d1, d2 = _dist(cur, prev), _dist(cur, nxt)
        if d1 < 1e-9 or d2 < 1e-9:
            out.append(cur)
            continue
        v1 = ((prev[0] - cur[0]) / d1, (prev[1] - cur[1]) / d1)
        v2 = ((nxt[0] - cur[0]) / d2, (nxt[1] - cur[1]) / d2)
        cos_t = max(-1.0, min(1.0, v1[0] * v2[0] + v1[1] * v2[1]))
        theta = math.acos(cos_t)
        if theta < 1e-6 or abs(math.pi - theta) < 1e-6:
            out.append(cur)
            continue
        # Tangent points sit r/tan(theta/2) back from the vertex; that is the
        # real fillet of radius r, not a fixed distance along each edge.
        back = r / math.tan(theta / 2.0)
        back = min(back, d1 / 2.0, d2 / 2.0)
        eff = back * math.tan(theta / 2.0)
        t1 = (cur[0] + v1[0] * back, cur[1] + v1[1] * back)
        t2 = (cur[0] + v2[0] * back, cur[1] + v2[1] * back)
        a0 = math.atan2(t1[1] - cur[1], t1[0] - cur[0])
        a1 = math.atan2(t2[1] - cur[1], t2[0] - cur[0])
        d = a1 - a0
        while d > math.pi:
            d -= 2 * math.pi
        while d < -math.pi:
            d += 2 * math.pi
        steps = max(3, int(round(20 * abs(d) / (math.pi / 2))))
        out.extend(
            (
                cur[0] + eff * math.cos(a0 + d * s / steps),
                cur[1] + eff * math.sin(a0 + d * s / steps),
            )
            for s in range(steps + 1)
        )
    return out


def rect(x, y, w, h, r=0.0):
    pts = [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
    return rounded_polygon(pts, r)


def circle(cx, cy, r, steps=180):
    return [
        (cx + r * math.cos(2 * math.pi * i / steps), cy + r * math.sin(2 * math.pi * i / steps))
        for i in range(steps)
    ]


def reverse(poly):
    return poly[::-1]


def ring(x, y, w, h, r, thickness):
    """A filleted outline: outer contour plus the inner one wound the other way,
    so the nonzero fill leaves the middle empty."""
    inner = rect(x + thickness, y + thickness, w - 2 * thickness, h - 2 * thickness,
                 max(0.0, r - thickness))
    return [rect(x, y, w, h, r), reverse(inner)]


def annulus(cx, cy, r_out, r_in, steps=240):
    """The same trick as ring(), for a circular bezel."""
    return [circle(cx, cy, r_out, steps), reverse(circle(cx, cy, r_in, steps))]


def bbox(polys):
    xs = [p[0] for poly in polys for p in poly]
    ys = [p[1] for poly in polys for p in poly]
    return min(xs), min(ys), max(xs), max(ys)


def move(polys, dx, dy):
    return [[(x + dx, y + dy) for x, y in poly] for poly in polys]


def xf(polys, k, dx=0.0, dy=0.0):
    return [[(x * k + dx, y * k + dy) for x, y in poly] for poly in polys]


def scale_layers(layers, k, dx=0.0, dy=0.0):
    return [
        (xf(polys, k, dx, dy), xf_paint(paint, k, dx, dy))
        for polys, paint in layers
    ]


