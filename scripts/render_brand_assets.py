# type: wordmarks set from the app's own Oswald outlines
# --------------------------------------------------------------------------- #

def _quad(p0, p1, p2, steps=10):
    out = []
    for i in range(1, steps + 1):
        t = i / steps
        u = 1 - t
        out.append(
            (
                u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0],
                u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1],
            )
        )
    return out


def _contour_poly(contour, steps=10):
    pts = list(contour)
    if not pts[0][2]:
        if not pts[-1][2]:
            pts = [((pts[0][0] + pts[-1][0]) / 2.0, (pts[0][1] + pts[-1][1]) / 2.0, True)] + pts
        else:
            pts = [pts[-1]] + pts[:-1]
    out = [(pts[0][0], pts[0][1])]
    i, n = 1, len(pts)
    while i <= n:
        p = pts[i % n]
        if p[2]:
            out.append((p[0], p[1]))
            i += 1
        else:
            q = pts[(i + 1) % n]
            out += _quad(out[-1], (p[0], p[1]), (q[0], q[1]), steps)
            i += 2
    return out


def wordmark(font, text, cap, tracking_em=0.0, x=0.0, y=0.0):
    """Set `text` in caps with an ink height of `cap`, top-left of the ink at
    (x, y). Returns closed polylines, y-down like the rest of the design."""
    missing = [ch for ch in text if font.gid(ch) == 0]
    if missing:
        raise ValueError("%r is not in the font" % "".join(missing))
    glyphs = []
    pen = 0.0
    for ch in text:
        gid = font.gid(ch)
        contours = [_contour_poly(c) for c in font.contours(gid)]
        glyphs.append((contours, pen))
        pen += font.advance(gid) + font.upem * tracking_em
    xs = [p[0] for polys, _ in glyphs for poly in polys for p in poly]
    ys = [p[1] for polys, _ in glyphs for poly in polys for p in poly]
    s = cap / (max(ys) - min(ys))
    tx = x - min(xs) * s
    ty = y + max(ys) * s
    return [
        [((p[0] + off) * s + tx, ty - p[1] * s) for p in poly]
        for polys, off in glyphs
        for poly in polys
    ]


def fitted_line(font, text, cap, target_w, max_tracking=0.34):
    """Set a secondary line so its ink measures exactly `target_w` by solving
    its tracking. Both lines of a lockup then share a measure, which is what
    makes a two-line lockup read as set rather than as stacked text."""
    base = wordmark(font, text, cap, 0.0)
    probe = wordmark(font, text, cap, 0.10)
    w0 = bbox(base)[2] - bbox(base)[0]
    slope = ((bbox(probe)[2] - bbox(probe)[0]) - w0) / 0.10
    if slope <= 1e-6:
        return base
    t = (target_w - w0) / slope
    return wordmark(font, text, cap, max(0.02, min(max_tracking, t)))


# --------------------------------------------------------------------------- #
# rasterizer: painter's algorithm into one straight-alpha float buffer
# --------------------------------------------------------------------------- #

def new_buffer(w, h):
    return array("f", b"\0" * (16 * w * h))


def _check(polys):
    """Catch a bare polyline where a list of them was meant: fill() would
    otherwise iterate its points and quietly draw an empty layer."""
    for poly in polys:
        if len(poly) < 3 or not isinstance(poly[0], (tuple, list)) or len(poly[0]) != 2:
            raise ValueError("shape is not a list of polylines: %r" % (poly,))


def _edges(polys):
    out = []
    for poly in polys:
        if len(poly) < 3:
            continue
        prev = poly[-1]
        for cur in poly:
            if prev[1] != cur[1]:
                out.append((prev[0], prev[1], cur[0], cur[1], 1 if cur[1] > prev[1] else -1))
            prev = cur
    return out


def fill(buf, w, h, polys, paint, ss=SS):
    """Fill closed polylines into the buffer with the nonzero rule.

    Coverage is exact across x and sampled on `ss` sub-scanlines down y, which
    is what keeps the long, near-horizontal edges of the play triangle and the
    type clean without supersampling the whole canvas.
    """
    _check(polys)
    es = _edges(polys)
    if not es:
        return
    y_lo = max(0, int(math.floor(min(min(e[1], e[3]) for e in es))))
    y_hi = min(h, int(math.ceil(max(max(e[1], e[3]) for e in es))))
    flat = constant_in_x(paint)
    for sub in range(y_lo * ss, y_hi * ss):
        yc = (sub + 0.5) / ss
        cross = []
        for ax, ay, bx, by, d in es:
            if (ay <= yc < by) or (by <= yc < ay):
                cross.append((ax + (yc - ay) / (by - ay) * (bx - ax), d))
        if len(cross) < 2:
            continue
        cross.sort()
        spans = []
        wind = 0
        start = None
        for xc, d in cross:
            if wind == 0:
                start = xc
            wind += d
            if wind == 0 and start is not None:
                if xc > start:
                    spans.append((start, xc))
                start = None
        if not spans:
            continue
        row = (sub // ss) * w
        fixed = paint_at(paint, 0.0, yc) if flat else None
        inv = 1.0 / ss
        for a, b in spans:
            gx0 = max(0, int(math.floor(a)))
            gx1 = min(w, int(math.ceil(b)))
            for gx in range(gx0, gx1):
                cov = min(b, gx + 1.0) - max(a, float(gx))
                if cov <= 0:
                    continue
                c = fixed if fixed is not None else paint_at(paint, gx + 0.5, yc)
                sa = cov * inv * c[3]
                if sa <= 0.0:
                    continue
                if sa > 1.0:
                    sa = 1.0
                i = (row + gx) * 4
                da = buf[i + 3]
                oa = sa + da * (1.0 - sa)
                if oa <= 0.0:
                    continue
                wd = da * (1.0 - sa)
                buf[i] = (c[0] * sa + buf[i] * wd) / oa
                buf[i + 1] = (c[1] * sa + buf[i + 1] * wd) / oa
                buf[i + 2] = (c[2] * sa + buf[i + 2] * wd) / oa
                buf[i + 3] = oa


def render(layers, w, h, ss=SS):
    buf = new_buffer(w, h)
    for polys, paint in layers:
        fill(buf, w, h, polys, paint, ss)
    return buf


def blit(dst, dw, dh, src, sw, sh, ox, oy):
    """src-over one rendered buffer onto another (used for the review sheet)."""
    for y in range(sh):
        ty = y + oy
        if ty < 0 or ty >= dh:
            continue
        srow = y * sw * 4
        drow = ty * dw * 4
        for x in range(sw):
            tx = x + ox
            if tx < 0 or tx >= dw:
                continue
            si = srow + x * 4
            sa = src[si + 3]
            if sa <= 0.0:
                continue
            di = drow + tx * 4
            if sa >= 1.0:
                dst[di] = src[si]
                dst[di + 1] = src[si + 1]
                dst[di + 2] = src[si + 2]
                dst[di + 3] = 1.0
                continue
            da = dst[di + 3]
            oa = sa + da * (1.0 - sa)
            wd = da * (1.0 - sa)
            dst[di] = (src[si] * sa + dst[di] * wd) / oa
            dst[di + 1] = (src[si + 1] * sa + dst[di + 1] * wd) / oa
            dst[di + 2] = (src[si + 2] * sa + dst[di + 2] * wd) / oa
            dst[di + 3] = oa


# --------------------------------------------------------------------------- #
# encoders: PNG (stdlib zlib), SVG, Android vector drawable
# --------------------------------------------------------------------------- #

def _png_chunk(tag, data):
    return (
        struct.pack(">I", len(data))
        + tag
        + data
        + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    )


def png_bytes(buf, w, h, alpha=True):
    lanes = 4 if alpha else 3
    vals = bytes(min(255, max(0, int(v * 255.0 + 0.5))) for v in buf)
    if alpha:
        body = vals
    else:
        body = bytearray(w * h * lanes)
        body[0::3] = vals[0::4]
        body[1::3] = vals[1::4]
        body[2::3] = vals[2::4]
        body = bytes(body)
    stride = w * lanes
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw += body[y * stride:(y + 1) * stride]
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6 if alpha else 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + _png_chunk(b"IEND", b"")
    )


def _hexc(c):
    return "%02X%02X%02X" % (
        min(255, max(0, int(c[0] * 255 + 0.5))),
        min(255, max(0, int(c[1] * 255 + 0.5))),
        min(255, max(0, int(c[2] * 255 + 0.5))),
    )


def _argb(c):
    """#AARRGGBB, the form Android's resources want."""
    return "#%02X%s" % (min(255, max(0, int(c[3] * 255 + 0.5))), _hexc(c))


def _poly_d(polys, prec=2):
    fmt = "%%.%df %%.%df " % (prec, prec)
    out = []
    for poly in polys:
        if len(poly) < 3:
            continue
        out.append("M")
        out.append("".join(fmt % p for p in poly) + "Z")
    return " ".join(out)


def svg_doc(layers, w, h, title):
    defs = []
    body = []
    n = 0
    for polys, paint in layers:
        if paint[0] == "solid":
            fill = _hexc(paint[1])
            extra = "" if paint[1][3] >= 1.0 else ' fill-opacity="%.3f"' % paint[1][3]
        else:
            n += 1
            gid = "g%d" % n
            if paint[0] == "lin":
                (x0, y0), (x1, y1), c0, c1 = paint[1], paint[2], paint[3], paint[4]
                defs.append(
                    '<linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="%.2f" y1="%.2f" '
                    'x2="%.2f" y2="%.2f"><stop offset="0" stop-color="#%s" stop-opacity="%.3f"/>'
                    '<stop offset="1" stop-color="#%s" stop-opacity="%.3f"/></linearGradient>'
                    % (gid, x0, y0, x1, y1, _hexc(c0), c0[3], _hexc(c1), c1[3])
                )
            else:
                (cx, cy), r, c, a, gamma = paint[1], paint[2], paint[3], paint[4], paint[5]
                stops = "".join(
                    '<stop offset="%.2f" stop-color="#%s" stop-opacity="%.3f"/>'
                    % (t, _hexc(c), a * (1.0 - t) ** gamma)
                    for t in (0.0, 0.25, 0.5, 0.75, 1.0)
                )
                defs.append(
                    '<radialGradient id="%s" gradientUnits="userSpaceOnUse" cx="%.2f" cy="%.2f" '
                    'r="%.2f">%s</radialGradient>' % (gid, cx, cy, r, stops)
                )
            fill = "url(#%s)" % gid
            extra = ""
        body.append('<path d="%s" fill="%s"%s/>' % (_poly_d(polys), fill, extra))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<svg xmlns="http://www.w3.org/2000/svg" width="%g" height="%g" viewBox="0 0 %g %g" '
        'role="img" aria-label="%s">\n<title>%s</title>\n<defs>%s</defs>\n%s\n</svg>\n'
        % (w, h, w, h, title, title, "".join(defs), "\n".join(body))
    )


def vector_xml(size, w, h, shapes, desc):
    """shapes: [(path_d, paint)] -- paint is a solid RGBA, a linear gradient or a
    radial one. A gradient paint is written as an <aapt:attr> inline colour, so
    the layer stays a plain vector drawable to every API level that can read
    one. Android's <gradient> takes two colours and no falloff exponent, so a
    radial paints its centre colour to fully transparent and the softness comes
    from the alpha pair (the raster and the SVG keep the exact curve)."""
    body = []
    for d, paint in shapes:
        if paint[0] == "solid":
            body.append(
                '    <path\n        android:fillColor="%s"\n        android:pathData="%s" />'
                % (_argb(paint[1]), d)
            )
            continue
        if paint[0] == "lin":
            (x0, y0), (x1, y1), c0, c1 = paint[1], paint[2], paint[3], paint[4]
            gradient = (
                '                android:type="linear"\n'
                '                android:startX="%.2f"\n                android:startY="%.2f"\n'
                '                android:endX="%.2f"\n                android:endY="%.2f"\n'
                '                android:startColor="%s"\n'
                '                android:endColor="%s" />\n'
                % (x0, y0, x1, y1, _argb(c0), _argb(c1))
            )
        else:
            (cx, cy), r, c, a = paint[1], paint[2], paint[3], paint[4]
            gradient = (
                '                android:type="radial"\n'
                '                android:centerX="%.2f"\n                android:centerY="%.2f"\n'
                '                android:gradientRadius="%.2f"\n'
                '                android:startColor="%s"\n'
                '                android:endColor="%s" />\n'
                % (cx, cy, r, _argb((c[0], c[1], c[2], a)), _argb((c[0], c[1], c[2], 0.0)))
            )
        body.append(
            '    <path android:pathData="%s">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient\n%s'
            '        </aapt:attr>\n'
            '    </path>' % (d, gradient)
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- %s -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="%gdp"\n    android:height="%gdp"\n'
        '    android:viewportWidth="%g"\n    android:viewportHeight="%g">\n%s\n</vector>\n'
        % (desc, size, size, w, h, "\n".join(body))
    )


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = "wb" if isinstance(data, (bytes, bytearray)) else "w"
    with open(path, mode) as fh:
        fh.write(data)
    return os.path.relpath(path, ROOT)


# --------------------------------------------------------------------------- #
# the mark: a brass play button -- a bezelled ring with the play triangle set
# into it, which is the shape a viewer already reads as "watch something"
# before they read a single letter. The brand sits in the material rather than
# in an abstract monogram: the app's brass, lit from above, on a glass face.
# --------------------------------------------------------------------------- #

MARK_RING = 0.070       # bezel thickness, as a fraction of the button's diameter
MARK_FACE = 0.11        # alpha of the glass face inside the bezel
MARK_TRI_H = 0.52       # triangle height, as a fraction of the diameter
MARK_TRI_ASPECT = 0.88  # width / height; a play glyph is taller than it is wide
MARK_FILLET = 0.085     # triangle corner fillet, as a fraction of its height
MARK_NUDGE = 0.020      # optical centring: a triangle's mass sits left of its box
MARK_D = 58.0           # the button's diameter in every lockup, so the mark-to-
                        # wordmark ratio is the same on the banner and the logo


def mark(d, x=0.0, y=0.0):
    """The button as one path: the bezel (an annulus is two contours, so it
    fills as a ring under the nonzero rule) plus the play glyph inside it.
    `d` is the button's diameter; (x, y) is the top-left of its bounding box."""
    bezel, tri = mark_split(d, x, y)
    return bezel + tri


def mark_split(d, x=0.0, y=0.0):
    """The same geometry as two pieces -- (bezel polys, glyph polys) -- so each
    can take its own fill. The glyph is nudged right of the geometric centre:
    a triangle's mass sits to the left of its bounding box, and centring the box
    is what leaves a play mark looking off-centre."""
    cx, cy = x + d / 2.0, y + d / 2.0
    r_in = d / 2.0 * (1.0 - 2.0 * MARK_RING)
    tri_h = MARK_TRI_H * d
    tri_w = tri_h * MARK_TRI_ASPECT
    tx = cx - tri_w / 2.0 + MARK_NUDGE * d
    ty = cy - tri_h / 2.0
    return (
        annulus(cx, cy, d / 2.0, r_in),
        [rounded_polygon(
            [(tx, ty), (tx + tri_w, cy), (tx, ty + tri_h)], MARK_FILLET * tri_h
        )],
    )


def mark_layers(d, x, y):
    """The mark alone, lit from above (the theme's projector-bulb warmth): the
    glass face first, then the bezel, then the brightest piece, the glyph."""
    cx, cy = x + d / 2.0, y + d / 2.0
    bezel, tri = mark_split(d, x, y)
    return [
        ([circle(cx, cy, d / 2.0 * (1.0 - 2.0 * MARK_RING))],
         rad((cx, cy - 0.06 * d), 0.62 * d, BRASS, MARK_FACE)),
        (bezel, lin((0.0, y), (0.0, y + d), BRASS, BRASS_LO)),
        (tri, lin((0.0, y), (0.0, y + d), BRASS_HI, BRASS)),
    ]


