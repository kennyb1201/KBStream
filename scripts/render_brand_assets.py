    total = mark_d + gap + word_w
    x0 = (LOGO_W - total) / 2.0
    mark_y = (LOGO_H - mark_d) / 2.0
    text_x = x0 + mark_d + gap
    block_top = (LOGO_H - (29.0 + 12.0 + 8.0)) / 2.0
    layers = mark_layers(mark_d, x0, mark_y)
    layers.append((move(word, text_x, block_top), solid(TEXT_HI)))
    layers.append((move(tag, text_x, block_top + 29.0 + 12.0), solid(TEXT_LO)))
    return layers


